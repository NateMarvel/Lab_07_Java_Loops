public class Counting_for_Loops
{
    public static void main(String[] args)
    {
            for (int count = 0; count <= 30; count++) {
                System.out.print(count + " ");
            }
        System.out.println();
        System.out.println();
            for (int count2 = 30; count2 >= 0; count2--){
                System.out.print(count2 + " ");
            }
        System.out.println();
        System.out.println();
            for (int count3 = 0; count3 <= 18; count3 = count3 + 3) {
                System.out.print(count3 + " ");
            }
        System.out.println();
        System.out.println();
            for (int count4 = 10; count4 >= 0; count4 = count4 - 2) {
                System.out.print(count4 + " ");
            }
    }
}
